-- این اسکریپت را در Supabase > SQL Editor اجرا کنید.
create table if not exists public.guests (
 id bigint generated by default as identity primary key,
 name text not null check(char_length(name) between 2 and 70),
 phone text not null unique,
 response text not null check(response in ('yes','no','maybe')),
 created_at timestamptz not null default now()
);
alter table public.guests enable row level security;
drop policy if exists "Public can submit RSVP" on public.guests;
create policy "Public can submit RSVP" on public.guests for insert to anon,authenticated
with check(char_length(name) between 2 and 70 and response in ('yes','no','maybe') and phone ~ '^(\+98|0098|0)?9[0-9]{9}$');
drop policy if exists "Admins can read guests" on public.guests;
create policy "Admins can read guests" on public.guests for select to authenticated using(auth.uid() is not null);

-- تنظیمات دورهمی: مهمان‌ها فقط می‌توانند بخوانند؛ فقط مدیر واردشده ویرایش می‌کند.
create table if not exists public.event_settings(
 id integer primary key check(id=1),
 title text not null default 'دورهمی دوستانه',
 location text not null default 'به‌زودی اعلام می‌شود',
 event_date text not null default 'به‌زودی اعلام می‌شود',
 description text not null default '',
 image_url text,
 updated_at timestamptz not null default now()
);
insert into public.event_settings(id) values(1) on conflict(id) do nothing;
alter table public.event_settings enable row level security;
drop policy if exists "Anyone can view event details" on public.event_settings;
create policy "Anyone can view event details" on public.event_settings for select to anon,authenticated using(true);
drop policy if exists "Admins can manage event details" on public.event_settings;
create policy "Admins can manage event details" on public.event_settings for all to authenticated using(auth.uid() is not null) with check(auth.uid() is not null);

-- فضای ذخیره عکس عمومی برای نمایش تصویر دورهمی؛ بارگذاری فقط برای مدیر واردشده.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('event-images','event-images',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict(id) do update set public=true,file_size_limit=5242880,allowed_mime_types=array['image/jpeg','image/png','image/webp'];
drop policy if exists "Admins upload event images" on storage.objects;
create policy "Admins upload event images" on storage.objects for insert to authenticated with check(bucket_id='event-images' and auth.uid() is not null);
drop policy if exists "Admins update event images" on storage.objects;
create policy "Admins update event images" on storage.objects for update to authenticated using(bucket_id='event-images' and auth.uid() is not null) with check(bucket_id='event-images' and auth.uid() is not null);
drop policy if exists "Public can view event images" on storage.objects;
create policy "Public can view event images" on storage.objects for select to anon,authenticated using(bucket_id='event-images');

